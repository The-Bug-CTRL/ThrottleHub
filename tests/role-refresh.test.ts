import { it, expect, vi } from "vitest";
type TestUser = { uid: string; getIdToken?: ReturnType<typeof vi.fn>; getIdTokenResult?: ReturnType<typeof vi.fn> };
const h = vi.hoisted(() => ({ effect: (() => {}) as () => void | (() => void), state: {} as Record<string, unknown>, user: null as TestUser | null, loading: false, listener: (async () => {}) as (user: TestUser | null) => Promise<void>, stop: vi.fn() }));
vi.mock("react", () => ({ useEffect: (effect: typeof h.effect) => { h.effect = effect; }, useState: (initial: unknown) => [Object.keys(h.state).length ? h.state : initial, (state: Record<string, unknown>) => { h.state = state; }] }));
vi.mock("firebase/auth", () => ({ onIdTokenChanged: (_: unknown, listener: typeof h.listener) => { h.listener = listener; return h.stop; } }));
vi.mock("@/lib/firebase", () => ({ auth: {} }));
vi.mock("../src/components/session", () => ({ useSession: () => ({ user: h.user, loading: h.loading }) }));
import { useRole } from "../src/components/use-role";
it("tracks refreshed strict claims, clears stale identities, fails closed and unsubscribes", async () => {
  h.state = {}; h.loading = true; h.user = null;
  expect(useRole().checking).toBe(true);
  h.loading = false;
  expect(useRole().admin).toBe(false);
  const token = vi.fn().mockResolvedValue({ claims: {} });
  h.user = { uid: "A", getIdToken: vi.fn().mockResolvedValue("unused"), getIdTokenResult: token };
  useRole(); const cleanup = h.effect();
  await h.listener(h.user);
  expect(useRole()).toMatchObject({ admin: false, checking: false });
  token.mockResolvedValue({ claims: { admin: true } });
  await h.listener(h.user);
  expect(useRole().admin).toBe(true);
  expect(h.user.getIdToken).toHaveBeenCalledTimes(1);
  expect(token).toHaveBeenLastCalledWith();
  token.mockResolvedValue({ claims: { admin: "true", moderator: true } });
  await h.listener(h.user);
  expect(useRole()).toMatchObject({ admin: false, moderator: true });
  token.mockRejectedValue(Error("offline"));
  await h.listener(h.user);
  expect(useRole()).toMatchObject({ admin: false, moderator: false });
  expect(useRole().error).toContain("could not be checked");
  h.user = { uid: "B" };
  expect(useRole()).toMatchObject({ admin: false, checking: true });
  if (cleanup) cleanup();
  expect(h.stop).toHaveBeenCalled();
});
